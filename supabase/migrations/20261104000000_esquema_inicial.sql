-- =====================================================================
-- Gerenciador de Estoque e Vídeos: esquema inicial do banco (Supabase)
-- =====================================================================
-- Tabelas
--   perfis         pessoas da equipe (ligadas ao login do Supabase Auth)
--   contas_tiktok  contas onde os vídeos são postados (OFICIAL, RICARDO...)
--   fabricantes    lista única de fabricantes (evita "DIXON JEANS" x "dixon jeans")
--   produtos       estoque: local, prateleira, descrição, peças, fabricante
--   videos         cada vídeo postado: produto, conta, quem postou e quando
--   registros      histórico automático de tudo o que foi alterado
-- Views (para as telas de análise)
--   v_produtos_resumo, v_videos_semana, v_videos_por_pessoa
--
-- Regras importantes garantidas pelo próprio banco:
--   * A data e a hora do vídeo são sempre as do servidor, no momento do registro.
--   * Admins master fixos (Ricardo e Márcio) não perdem o cargo e não são excluídos.
--   * Ninguém muda o próprio cargo.
--   * Só admin master vê os registros e gerencia a equipe.
--   * "Excluir conta" desativa a pessoa: ela perde o acesso, mas o histórico fica.
-- =====================================================================

set check_function_bodies = off;

-- ---------------------------------------------------------------------
-- Tipos
-- ---------------------------------------------------------------------
create type public.papel_usuario as enum ('admin', 'colaborador');

-- ---------------------------------------------------------------------
-- perfis: uma linha por pessoa da equipe, com o mesmo id do login
-- ---------------------------------------------------------------------
create table public.perfis (
  id            uuid primary key references auth.users (id) on delete cascade,
  nome          text not null check (length(trim(nome)) > 0),
  email         text not null unique,
  papel         public.papel_usuario not null default 'colaborador',
  fixo          boolean not null default false,   -- admin master fixo
  ativo         boolean not null default true,    -- false = conta excluída
  criado_em     timestamptz not null default now(),
  excluido_em   timestamptz,
  constraint fixo_sempre_admin check (not fixo or papel = 'admin'),
  constraint fixo_sempre_ativo check (not fixo or ativo)
);
comment on table public.perfis is 'Pessoas da equipe. "Excluir conta" marca ativo = false para manter o histórico.';

-- ---------------------------------------------------------------------
-- contas_tiktok
-- ---------------------------------------------------------------------
create table public.contas_tiktok (
  id        smallint generated by default as identity primary key,
  nome      text not null unique check (nome = upper(trim(nome)) and length(nome) > 0),
  ordem     smallint not null default 0,         -- ordem de exibição (como na planilha)
  ativa     boolean not null default true,
  criado_em timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- fabricantes
-- ---------------------------------------------------------------------
create table public.fabricantes (
  id        integer generated by default as identity primary key,
  nome      text not null unique check (nome = upper(trim(nome)) and length(nome) > 0),
  criado_em timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- produtos: o id é o "ID automático" (#0001, #0002...)
-- ---------------------------------------------------------------------
create table public.produtos (
  id             bigint generated by default as identity primary key,
  local          smallint not null check (local between 1 and 9),
  prateleira     text not null unique check (prateleira ~ '^[A-Z]{1,2}[0-9]{1,2}$'),
  descricao      text not null default '',
  quantidade     integer not null default 0 check (quantidade >= 0),
  fabricante_id  integer references public.fabricantes (id) on delete set null,
  link_tiktok    text check (link_tiktok is null or link_tiktok ~ '^https://'),
  criado_em      timestamptz not null default now(),
  criado_por     uuid references public.perfis (id),
  atualizado_em  timestamptz not null default now(),
  atualizado_por uuid references public.perfis (id)
);
comment on column public.produtos.prateleira is 'Nº da prateleira como na planilha: letra(s) + posição, ex.: A1, M12. Única no estoque.';
create index produtos_fabricante_idx on public.produtos (fabricante_id);
create index produtos_local_idx on public.produtos (local);

-- ---------------------------------------------------------------------
-- videos
-- ---------------------------------------------------------------------
create table public.videos (
  id          bigint generated by default as identity primary key,
  produto_id  bigint not null references public.produtos (id) on delete restrict,
  conta_id    smallint not null references public.contas_tiktok (id) on delete restrict,
  usuario_id  uuid not null references public.perfis (id) on delete restrict,
  postado_em  timestamptz not null default now()   -- sempre a hora do servidor (ver gatilho)
);
create index videos_produto_idx on public.videos (produto_id, postado_em desc);
create index videos_usuario_idx on public.videos (usuario_id, postado_em desc);
create index videos_conta_idx   on public.videos (conta_id, postado_em desc);
create index videos_data_idx    on public.videos (postado_em desc);

-- ---------------------------------------------------------------------
-- registros: histórico de alterações, preenchido só pelos gatilhos
-- ---------------------------------------------------------------------
create table public.registros (
  id            bigint generated always as identity primary key,
  usuario_id    uuid references public.perfis (id),
  acao          text not null,     -- 'Adicionou produto', 'Editou produto', 'Registrou vídeo'...
  tabela        text not null,
  registro_id   text not null,
  detalhe       text not null default '',
  mudancas      jsonb,             -- {"quantidade": {"de": 8, "para": 5}, ...}
  criado_em     timestamptz not null default now()
);
create index registros_data_idx    on public.registros (criado_em desc);
create index registros_usuario_idx on public.registros (usuario_id, criado_em desc);


-- =====================================================================
-- Funções auxiliares de permissão
-- =====================================================================

-- A pessoa logada tem conta ativa?
create or replace function public.usuario_ativo()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.perfis
    where id = (select auth.uid()) and ativo
  );
$$;

-- A pessoa logada é admin master ativo?
create or replace function public.eh_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.perfis
    where id = (select auth.uid()) and ativo and papel = 'admin'
  );
$$;

revoke all on function public.usuario_ativo() from public;
revoke all on function public.eh_admin() from public;
grant execute on function public.usuario_ativo() to authenticated;
grant execute on function public.eh_admin() to authenticated;


