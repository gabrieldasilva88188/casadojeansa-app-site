-- Cria o perfil automaticamente quando alguém se cadastra (sempre como colaborador)
create or replace function public.criar_perfil_novo_usuario()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.perfis (id, nome, email)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'nome'), ''), split_part(new.email, '@', 1)),
    lower(new.email)
  );
  return new;
end;
$$;

create trigger ao_criar_usuario
  after insert on auth.users
  for each row execute function public.criar_perfil_novo_usuario();


-- Protege a equipe: admins fixos, próprio cargo e quem pode mudar o quê
create or replace function public.proteger_perfil()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  quem uuid := (select auth.uid());
begin
  -- Alterações feitas pelo painel/servidor (sem usuário logado) passam direto
  if quem is null then
    return new;
  end if;

  -- Campos que nunca mudam pelo app
  if new.id <> old.id or new.email <> old.email or new.criado_em <> old.criado_em then
    raise exception 'Esses dados do perfil não podem ser alterados pelo sistema.';
  end if;
  if new.fixo <> old.fixo then
    raise exception 'Só o responsável técnico pode definir admins master fixos.';
  end if;

  -- Admin master fixo: não perde o cargo e não é excluído
  if old.fixo and (new.papel <> 'admin' or not new.ativo) then
    raise exception '% é admin master fixo: o cargo não muda e a conta não pode ser excluída.', old.nome;
  end if;

  -- Ninguém muda o próprio cargo nem exclui a própria conta
  if old.id = quem and (new.papel <> old.papel or new.ativo <> old.ativo) then
    raise exception 'Você não pode mudar o próprio cargo nem excluir a própria conta.';
  end if;

  -- Cargo e exclusão: só admin master
  if (new.papel <> old.papel or new.ativo <> old.ativo) and not public.eh_admin() then
    raise exception 'Só admin master pode mudar cargos e excluir contas.';
  end if;

  -- Colaborador só pode mudar o próprio nome
  if old.id <> quem and not public.eh_admin() then
    raise exception 'Você só pode alterar o seu próprio perfil.';
  end if;

  if old.ativo and not new.ativo then
    new.excluido_em := now();
  elsif new.ativo and not old.ativo then
    new.excluido_em := null;
  end if;

  return new;
end;
$$;

create trigger proteger_perfil
  before update on public.perfis
  for each row execute function public.proteger_perfil();


-- Produtos: guarda quem criou/alterou e quando
create or replace function public.carimbar_produto()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.criado_em := now();
    new.criado_por := coalesce((select auth.uid()), new.criado_por);
  end if;
  new.atualizado_em := now();
  new.atualizado_por := coalesce((select auth.uid()), new.atualizado_por, new.criado_por);
  return new;
end;
$$;

create trigger carimbar_produto
  before insert or update on public.produtos
  for each row execute function public.carimbar_produto();


-- Vídeos: data/hora e autor sempre definidos pelo servidor
create or replace function public.carimbar_video()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if (select auth.uid()) is not null then
    new.usuario_id := (select auth.uid());   -- quem está logado é quem postou
    new.postado_em := now();                 -- hora do sistema, não a do celular
  end if;
  return new;
end;
$$;

create trigger carimbar_video
  before insert on public.videos
  for each row execute function public.carimbar_video();


-- Histórico automático (tabela registros)
create or replace function public.registrar_alteracao()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_acao     text;
  v_detalhe  text := '';
  v_mudancas jsonb;
  v_antes    jsonb;
  v_depois   jsonb;
  v_campos   text[];
  v_campo    text;
  v_prod     record;
  v_conta    text;
begin
  if tg_table_name = 'produtos' then
    if tg_op = 'INSERT' then
      v_acao := 'Adicionou produto';
      v_detalhe := new.prateleira || ' ' || new.descricao || ' (ID #' || lpad(new.id::text, 4, '0') || ')';
    else
      v_antes  := to_jsonb(old);
      v_depois := to_jsonb(new);
      v_campos := array['local', 'prateleira', 'descricao', 'quantidade', 'fabricante_id', 'link_tiktok'];
      v_mudancas := '{}'::jsonb;
      foreach v_campo in array v_campos loop
        if v_antes -> v_campo is distinct from v_depois -> v_campo then
          v_mudancas := v_mudancas || jsonb_build_object(
            v_campo, jsonb_build_object('de', v_antes -> v_campo, 'para', v_depois -> v_campo));
        end if;
      end loop;
      if v_mudancas = '{}'::jsonb then
        return new;   -- nada relevante mudou
      end if;
      v_acao := 'Editou produto';
      v_detalhe := old.prateleira || ': ' || (
        select string_agg(k, ', ' order by k) from jsonb_object_keys(v_mudancas) as k);
    end if;
    insert into public.registros (usuario_id, acao, tabela, registro_id, detalhe, mudancas)
    values ((select auth.uid()), v_acao, 'produtos', new.id::text, v_detalhe, v_mudancas);

  elsif tg_table_name = 'videos' then
    select p.prateleira, p.descricao into v_prod from public.produtos p where p.id = new.produto_id;
    select c.nome into v_conta from public.contas_tiktok c where c.id = new.conta_id;
    insert into public.registros (usuario_id, acao, tabela, registro_id, detalhe)
    values (new.usuario_id, 'Registrou vídeo', 'videos', new.id::text,
            v_prod.prateleira || ' ' || v_prod.descricao || ' na conta ' || v_conta);

  elsif tg_table_name = 'perfis' then
    if tg_op = 'INSERT' then
      insert into public.registros (usuario_id, acao, tabela, registro_id, detalhe)
      values (new.id, 'Criou conta', 'perfis', new.id::text, new.nome);
    else
      if new.papel <> old.papel then
        insert into public.registros (usuario_id, acao, tabela, registro_id, detalhe, mudancas)
        values ((select auth.uid()), 'Alterou cargo', 'perfis', new.id::text,
                new.nome || ': ' || replace(old.papel::text, 'admin', 'admin master') || ' → ' ||
                replace(new.papel::text, 'admin', 'admin master'),
                jsonb_build_object('papel', jsonb_build_object('de', old.papel, 'para', new.papel)));
      end if;
      if old.ativo and not new.ativo then
        insert into public.registros (usuario_id, acao, tabela, registro_id, detalhe)
        values ((select auth.uid()), 'Excluiu conta', 'perfis', new.id::text, new.nome || ' (' || new.email || ')');
      elsif new.ativo and not old.ativo then
        insert into public.registros (usuario_id, acao, tabela, registro_id, detalhe)
        values ((select auth.uid()), 'Reativou conta', 'perfis', new.id::text, new.nome || ' (' || new.email || ')');
      end if;
    end if;
  end if;
  return new;
end;
$$;

create trigger registrar_produto
  after insert or update on public.produtos
  for each row execute function public.registrar_alteracao();

create trigger registrar_video
  after insert on public.videos
  for each row execute function public.registrar_alteracao();

create trigger registrar_perfil
  after insert or update on public.perfis
  for each row execute function public.registrar_alteracao();


-- =====================================================================
-- Segurança por linha (RLS): quem vê e quem altera o quê
-- =====================================================================
alter table public.perfis        enable row level security;
alter table public.contas_tiktok enable row level security;
alter table public.fabricantes   enable row level security;
alter table public.produtos      enable row level security;
alter table public.videos        enable row level security;
alter table public.registros     enable row level security;

-- Ninguém sem login acessa nada
revoke all on all tables in schema public from anon;

-- perfis: equipe ativa vê a equipe; mudanças passam pelo gatilho proteger_perfil
create policy "equipe vê a equipe" on public.perfis
  for select to authenticated
  using (public.usuario_ativo() or id = (select auth.uid()));
create policy "admin ou o próprio altera perfil" on public.perfis
  for update to authenticated
  using (public.eh_admin() or id = (select auth.uid()))
  with check (public.eh_admin() or id = (select auth.uid()));
-- (sem política de insert/delete: perfis nascem pelo cadastro e nunca são apagados)

-- contas_tiktok: todos veem; admin cadastra e altera
create policy "equipe vê contas" on public.contas_tiktok
  for select to authenticated using (public.usuario_ativo());
create policy "admin cria contas" on public.contas_tiktok
  for insert to authenticated with check (public.eh_admin());
create policy "admin altera contas" on public.contas_tiktok
  for update to authenticated using (public.eh_admin()) with check (public.eh_admin());

-- fabricantes: todos veem e cadastram (ao adicionar produto)
create policy "equipe vê fabricantes" on public.fabricantes
  for select to authenticated using (public.usuario_ativo());
create policy "equipe cria fabricantes" on public.fabricantes
  for insert to authenticated with check (public.usuario_ativo());

-- produtos: toda a equipe vê, adiciona e edita; só admin exclui
create policy "equipe vê produtos" on public.produtos
  for select to authenticated using (public.usuario_ativo());
create policy "equipe adiciona produtos" on public.produtos
  for insert to authenticated with check (public.usuario_ativo());
create policy "equipe edita produtos" on public.produtos
  for update to authenticated using (public.usuario_ativo()) with check (public.usuario_ativo());
create policy "admin exclui produtos" on public.produtos
  for delete to authenticated using (public.eh_admin());

-- videos: toda a equipe vê e registra (sempre em nome de quem está logado); só admin apaga
create policy "equipe vê vídeos" on public.videos
  for select to authenticated using (public.usuario_ativo());
create policy "equipe registra vídeos" on public.videos
  for insert to authenticated with check (public.usuario_ativo());
create policy "admin apaga vídeos" on public.videos
  for delete to authenticated using (public.eh_admin());

-- registros: só admin master lê; ninguém escreve direto (só os gatilhos)
create policy "admin vê registros" on public.registros
  for select to authenticated using (public.eh_admin());

-- Permissões mínimas para quem está logado (o RLS acima filtra as linhas)
revoke all on public.perfis, public.contas_tiktok, public.fabricantes,
              public.produtos, public.videos, public.registros from authenticated;
grant select, update (nome, papel, ativo) on public.perfis to authenticated;
grant select, insert, update on public.contas_tiktok to authenticated;
grant select, insert on public.fabricantes to authenticated;
grant select, insert, update, delete on public.produtos to authenticated;
grant select, insert, delete on public.videos to authenticated;
grant select on public.registros to authenticated;


-- =====================================================================
-- Views para as telas de análise (respeitam as regras de RLS acima)
-- =====================================================================

-- Um produto por linha, com contagem de vídeos e tempo sem vídeo
create view public.v_produtos_resumo
with (security_invoker = true) as
select
  p.id,
  '#' || lpad(p.id::text, 4, '0')                     as id_exibicao,
  p.local,
  p.prateleira,
  p.descricao,
  p.quantidade,
  f.nome                                              as fabricante,
  p.link_tiktok,
  p.criado_em,
  count(v.id)                                         as total_videos,
  count(v.id) filter (where v.postado_em >= now() - interval '30 days') as videos_30_dias,
  max(v.postado_em)                                   as ultimo_video,
  extract(day from now() - coalesce(max(v.postado_em), p.criado_em))::int as dias_sem_video
from public.produtos p
left join public.fabricantes f on f.id = p.fabricante_id
left join public.videos v      on v.produto_id = p.id
group by p.id, f.nome;

-- Vídeos por conta, mês e semana, no formato da planilha (01 a 03, 04 a 10...)
create view public.v_videos_semana
with (security_invoker = true) as
with base as (
  select
    c.id   as conta_id,
    c.nome as conta,
    c.ordem,
    (v.postado_em at time zone 'America/Sao_Paulo') as data_local
  from public.videos v
  join public.contas_tiktok c on c.id = v.conta_id
)
select
  conta_id,
  conta,
  ordem,
  date_trunc('month', data_local)::date as mes,
  case
    when extract(day from data_local) <= 3  then '01 a 03'
    when extract(day from data_local) <= 10 then '04 a 10'
    when extract(day from data_local) <= 17 then '11 a 17'
    when extract(day from data_local) <= 24 then '18 a 24'
    else '25 a 31'
  end as semana,
  count(*) as videos
from base
group by conta_id, conta, ordem, mes, semana;

-- Vídeos por pessoa (gráfico do Admin)
create view public.v_videos_por_pessoa
with (security_invoker = true) as
select
  pe.id   as usuario_id,
  pe.nome,
  pe.ativo,
  count(v.id) filter (where v.postado_em >= now() - interval '7 days')  as videos_7_dias,
  count(v.id) filter (where v.postado_em >= now() - interval '30 days') as videos_30_dias,
  count(v.id) as videos_total
from public.perfis pe
left join public.videos v on v.usuario_id = pe.id
group by pe.id;

grant select on public.v_produtos_resumo, public.v_videos_semana, public.v_videos_por_pessoa to authenticated;
