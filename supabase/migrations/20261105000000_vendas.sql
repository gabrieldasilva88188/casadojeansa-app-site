-- =====================================================================
-- Vendas do TikTok Shop (lançadas manualmente pelo admin master)
-- =====================================================================
-- O TikTok não permite exportar as vendas por vídeo, então o admin lança
-- quantas peças de cada produto foram vendidas em cada conta, por dia.
-- Só admin master vê, adiciona, edita e exclui vendas.
-- =====================================================================

create table public.vendas (
  id             bigint generated by default as identity primary key,
  produto_id     bigint not null references public.produtos (id) on delete restrict,
  conta_id       smallint not null references public.contas_tiktok (id) on delete restrict,
  quantidade     integer not null check (quantidade > 0),
  vendido_em     date not null default (now() at time zone 'America/Sao_Paulo')::date,
  criado_em      timestamptz not null default now(),
  criado_por     uuid references public.perfis (id),
  atualizado_em  timestamptz not null default now(),
  atualizado_por uuid references public.perfis (id),
  constraint venda_nao_futura check (vendido_em <= (criado_em at time zone 'America/Sao_Paulo')::date + 1)
);
comment on table public.vendas is 'Peças vendidas por produto, conta do TikTok e dia. Lançadas pelo admin master.';
create index vendas_data_idx    on public.vendas (vendido_em desc);
create index vendas_produto_idx on public.vendas (produto_id, vendido_em desc);
create index vendas_conta_idx   on public.vendas (conta_id, vendido_em desc);


-- Quem lançou/alterou e quando (definido pelo servidor)
create or replace function public.carimbar_venda()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.criado_em := now();
    new.criado_por := coalesce((select auth.uid()), new.criado_por);
  else
    new.criado_em := old.criado_em;
    new.criado_por := old.criado_por;
  end if;
  new.atualizado_em := now();
  new.atualizado_por := coalesce((select auth.uid()), new.atualizado_por, new.criado_por);
  return new;
end;
$$;

create trigger carimbar_venda
  before insert or update on public.vendas
  for each row execute function public.carimbar_venda();


-- Histórico: adicionou, editou e excluiu venda
create or replace function public.registrar_venda()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_linha    record;
  v_prod     record;
  v_conta    text;
  v_acao     text;
  v_mudancas jsonb;
  v_antes    jsonb;
  v_depois   jsonb;
  v_campo    text;
begin
  v_linha := case when tg_op = 'DELETE' then old else new end;
  select p.prateleira, p.descricao into v_prod from public.produtos p where p.id = v_linha.produto_id;
  select c.nome into v_conta from public.contas_tiktok c where c.id = v_linha.conta_id;

  if tg_op = 'INSERT' then
    v_acao := 'Adicionou venda';
  elsif tg_op = 'DELETE' then
    v_acao := 'Excluiu venda';
  else
    v_antes := to_jsonb(old);
    v_depois := to_jsonb(new);
    v_mudancas := '{}'::jsonb;
    foreach v_campo in array array['produto_id', 'conta_id', 'quantidade', 'vendido_em'] loop
      if v_antes -> v_campo is distinct from v_depois -> v_campo then
        v_mudancas := v_mudancas || jsonb_build_object(
          v_campo, jsonb_build_object('de', v_antes -> v_campo, 'para', v_depois -> v_campo));
      end if;
    end loop;
    if v_mudancas = '{}'::jsonb then
      return null;
    end if;
    v_acao := 'Editou venda';
  end if;

  insert into public.registros (usuario_id, acao, tabela, registro_id, detalhe, mudancas)
  values (
    (select auth.uid()), v_acao, 'vendas', v_linha.id::text,
    v_linha.quantidade || ' peça(s) de ' || v_prod.prateleira || ' ' || v_prod.descricao ||
      ' na conta ' || v_conta || ' em ' || to_char(v_linha.vendido_em, 'DD/MM/YYYY'),
    v_mudancas
  );
  return null;   -- gatilho "after": o valor de retorno é ignorado
end;
$$;

create trigger registrar_venda
  after insert or update or delete on public.vendas
  for each row execute function public.registrar_venda();


-- Segurança: só admin master
alter table public.vendas enable row level security;
revoke all on public.vendas from anon, authenticated;
grant select, insert, update, delete on public.vendas to authenticated;

create policy "admin vê vendas" on public.vendas
  for select to authenticated using (public.eh_admin());
create policy "admin adiciona vendas" on public.vendas
  for insert to authenticated with check (public.eh_admin());
create policy "admin edita vendas" on public.vendas
  for update to authenticated using (public.eh_admin()) with check (public.eh_admin());
create policy "admin exclui vendas" on public.vendas
  for delete to authenticated using (public.eh_admin());


-- Vendas por produto, conta, mês e semana (01 a 03, 04 a 10...), para gráficos e filtros
create view public.v_vendas_semana
with (security_invoker = true) as
select
  ve.produto_id,
  p.prateleira,
  p.descricao,
  ve.conta_id,
  c.nome                                   as conta,
  date_trunc('month', ve.vendido_em)::date as mes,
  case
    when extract(day from ve.vendido_em) <= 3  then '01 a 03'
    when extract(day from ve.vendido_em) <= 10 then '04 a 10'
    when extract(day from ve.vendido_em) <= 17 then '11 a 17'
    when extract(day from ve.vendido_em) <= 24 then '18 a 24'
    else '25 a 31'
  end                                      as semana,
  sum(ve.quantidade)::int                  as pecas_vendidas,
  count(*)::int                            as lancamentos
from public.vendas ve
join public.produtos p      on p.id = ve.produto_id
join public.contas_tiktok c on c.id = ve.conta_id
group by ve.produto_id, p.prateleira, p.descricao, ve.conta_id, c.nome, mes, semana;

grant select on public.v_vendas_semana to authenticated;
